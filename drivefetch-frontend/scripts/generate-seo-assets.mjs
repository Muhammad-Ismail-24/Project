/**
 * scripts/generate-seo-assets.mjs
 *
 * Writes public/robots.txt and public/sitemap.xml from VITE_SITE_URL.
 *
 * WHY THIS EXISTS
 * ---------------
 * The React app reads the domain from siteConfig (import.meta.env.VITE_SITE_URL),
 * so canonicals, OpenGraph and JSON-LD all follow a domain change automatically.
 * robots.txt and sitemap.xml cannot — they are served as static files and never
 * pass through the bundler.
 *
 * Left as hand-written files they would silently keep pointing at the old
 * domain after a switch: the sitemap would advertise URLs that 301 or 404, and
 * Search Console would reject it for being on a different host to the property.
 * That single inconsistency undoes the whole "one-line domain switch" guarantee.
 *
 * So they are generated from the same variable the app uses. Runs automatically
 * via the `prebuild` npm script; the output is committed so the dev server and
 * any deploy that skips the script still serve valid files.
 *
 * Run manually:  node scripts/generate-seo-assets.mjs
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PUBLIC_DIR = join(__dirname, '..', 'public');

const DEFAULT_URL = 'https://carfinderproject.vercel.app';
const SITE_URL = (process.env.VITE_SITE_URL || DEFAULT_URL).trim().replace(/\/+$/, '');

/**
 * Routes to expose to crawlers.
 *
 * Deliberately excluded:
 *   /saved  — per-user content behind auth; a crawler only ever sees an empty
 *             shell. It is marked noindex in the app for the same reason.
 *   /404    — soft-404, also noindex.
 */
const ROUTES = [
  { path: '/',            changefreq: 'daily',   priority: '1.0' },
  { path: '/recommend',   changefreq: 'weekly',  priority: '0.9' },
  { path: '/calculators', changefreq: 'monthly', priority: '0.9' },
  { path: '/chat',        changefreq: 'monthly', priority: '0.8' },
  { path: '/about',       changefreq: 'monthly', priority: '0.6' },
  { path: '/privacy',     changefreq: 'yearly',  priority: '0.3' },
];

const today = new Date().toISOString().slice(0, 10);

const robots = `# robots.txt — generated by scripts/generate-seo-assets.mjs
# Edit that script, not this file: it is overwritten on every build.

User-agent: *
Allow: /

# API and auth endpoints return JSON or redirects, never indexable content.
Disallow: /api/
Disallow: /auth/

# Per-user pages — nothing useful for a crawler, and noindex in the app too.
Disallow: /saved

Sitemap: ${SITE_URL}/sitemap.xml
`;

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-assets.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${ROUTES.map(
  ({ path, changefreq, priority }) => `  <url>
    <loc>${SITE_URL}${path === '/' ? '/' : path}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`
).join('\n')}
</urlset>
`;

mkdirSync(PUBLIC_DIR, { recursive: true });
writeFileSync(join(PUBLIC_DIR, 'robots.txt'), robots, 'utf8');
writeFileSync(join(PUBLIC_DIR, 'sitemap.xml'), sitemap, 'utf8');

console.log(`[seo] robots.txt + sitemap.xml written for ${SITE_URL}`);
console.log(`[seo] ${ROUTES.length} routes listed`);
